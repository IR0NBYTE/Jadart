"""Runtime-stub NAMES from the isolate snapshot's object-store roots.

Every stub-aware rule in the lifter keys off the callee's name: `_classify_stub` matches
`_iso_stub_<Base>Stub`, `_noreturn` asks it whether a `bl` throws, `_call_args` falls back
on it, and `_pin_call` treats a named stub as giving every register back. Those names used
to come from one of two places, and a default `flutter build apk --release` has neither: a
stub has no Function object in the snapshot, and the .so carries no symbol for one. So the
whole taxonomy was dead code on the build a user actually has, and a stub printed as an
ordinary Dart call: `sub_0x2d5d00(...)` where the machine throws and never comes back
(#234).

There is a third place, and it needs no symbols. After the fill pass an AOT program
snapshot writes its ROOTS: the isolate ObjectStore's pointer fields, in declaration order,
from `from()` through `to_snapshot(kFullAOT)` (app_snapshot.cc,
ProgramDeserializationRoots::ReadRoots). The tail of that run is the runtime stubs
generated code calls, each a Code object whose instructions-table slot jadart already maps
to a pc. So the root INDEX names the stub, and the index comes from a macro expansion of
the release's own header rather than from the binary's strings.

What makes that safe to act on is that the binary confirms it. A field inserted or dropped
shifts every later index, so the layout states which roots are Code-typed and the reader
checks all of them against the Code objects the fill pass recovered: 244 of 244 agree on
the 3.12.2 fixtures, and any disagreement means the layout does not describe this binary,
where naming nothing is the right answer. Two further cross-checks live in the tests
rather than here, because they cost a disassembly and a scan: that the root run ends
exactly where `dispatch.find_dispatch_table` independently anchors the dispatch table, and
that every named stub's body agrees with the return discipline its name implies (no `ret`
anywhere in a stub named as a throw).

Measured over the roots of seven binaries, three architectures (arm64, arm32, x64) and
both fixtures: 76 of 76 Code-typed roots resolve to a pc, no name collides with a snapshot
name, and the run ends at the dispatch table in every case.

Dart 3.13 moved the stubs. It folded the vm snapshot into the program's, so the root run
opens with the Roots struct and the class table, 1,518 refs ahead of the ObjectStore, and
the stubs are 173 handles inside that struct, in VM_STUB_CODE_LIST order; the ObjectStore
holds none. The reading is the same one, a root index that names a Code, and so is the
check: on the one 3.13 binary there is (FluffyChat's F-Droid build) the 173 stub roots
are Code, no other of the 1,689 roots is, and the run ends on the field tables and those
on the dispatch table. The names keep the `_iso_stub_` spelling, so the lifter's rules
read a 3.13 stub the way they read a 3.12 one.

Tables are generated by tools/gen_objstore.py from runtime/vm/object_store.h at a release
tag, and for 3.13 from roots.h and the lists it names. Do not hand-edit; regenerate, and
`--check` re-derives every bundled layout from its tag. One layout per distinct root run;
eleven cover the nineteen registered epochs. Only the 3.12.2 and 3.13.0 layouts have been
checked against real binaries, which is why the agreement check runs on every parse
rather than on the ones we doubt.
"""
from __future__ import annotations

from dataclasses import dataclass, field

from .stream import ReadStream, TruncatedSnapshot


@dataclass(frozen=True)
class RootLayout:
    """One release's AOT root run, as far as naming a stub needs it.

    `count` is how many refs the deserializer reads before the initial-field tables,
    `stubs` maps a root index to the stub's name in OBJECT_STORE_STUB_CODE_LIST, and
    `unnamed` holds the Code-typed roots that list does not name (the two method-extractor
    entries, through 3.3). Both are needed: the names are the output, and the full set of
    Code-typed indexes is what the binary gets checked against.

    From 3.13 the run opens with the Roots struct and the class table, and the stubs
    are Roots handles named by VM_STUB_CODE_LIST (tools/gen_objstore.py). `class_base`
    is the root index the class table starts at and `class_cids` the cid each of its
    roots is the Class of; -1 and empty before 3.13, whose roots hold no class table.
    verify's G3 reads them: a root run misplaced by one ref puts every class on the
    wrong cid."""

    count: int
    stubs: dict
    unnamed: frozenset = field(default_factory=frozenset)
    class_base: int = -1
    class_cids: tuple = ()

    @property
    def codes(self) -> frozenset:
        """Every root index this release declares as a Code field."""
        return frozenset(self.stubs) | self.unnamed


def class_roots(image, fr, epoch):
    """(cid, ref) for every class-table root, in the order read, or None.

    None when there is nothing to read: the release's roots hold no class table
    (everything before 3.13), there is no blob, or the fill walk did not reach the
    roots. An EMPTY list when the stream ends inside the root run, which is a
    different answer: the table should be there and is not. The caller compares each
    ref's Class against the cid; this only says which ref the layout puts on which."""
    layout = getattr(epoch, "roots", None) if epoch is not None else None
    if (layout is None or not layout.class_cids or image is None or not image.data
            or fr.end_pos <= 0):
        return None
    st = ReadStream(image.data, fr.end_pos)
    try:
        # Bounded by the layout, not the file: class_base and the cid list are the
        # generated table's, and each ref read takes a byte off the stream.
        for _ in range(layout.class_base):
            st.read_ref_id()
        return [(cid, st.read_ref_id()) for cid in layout.class_cids]
    except TruncatedSnapshot:
        return []


def stub_names(image, fr, epoch) -> dict:
    """pc_offset -> `_iso_stub_<Name>Stub` for every runtime stub the roots name.

    Empty when there is nothing to name with (an epoch with no layout, a snapshot whose
    fill walk did not reach the roots) or when the layout and the binary disagree about
    which roots are Code. A disagreement is a refusal: the alternative is naming a stub
    after its neighbour, which would be worse than leaving it as `sub_0x...`.

    The spelling is the one the VM's own symbols use (image_snapshot.cc), so the names
    reach `_classify_stub` exactly as a symbolized build's would, and no rule downstream
    has to learn a second form."""
    layout = getattr(epoch, "roots", None) if epoch is not None else None
    if layout is None or not image.data or fr.end_pos <= 0:
        return {}
    st = ReadStream(image.data, fr.end_pos)
    try:
        roots = [st.read_ref_id() for _ in range(layout.count)]
    except TruncatedSnapshot:
        return {}
    # Only the main (non-deferred) Code objects have an instructions-table slot, and every
    # stub is in the root unit, so this doubles as the "is this ref a Code?" test.
    pc_by_ref = {}
    for ref, _owner_ref, ci in fr.codes:
        slot = image.first_code + ci
        if 0 <= slot < len(image.pcs):
            pc_by_ref[ref] = image.pcs[slot]
    codes = layout.codes
    for i, ref in enumerate(roots):
        if (ref in pc_by_ref) != (i in codes):
            return {}
    return {pc_by_ref[roots[i]]: f"_iso_stub_{name}Stub"
            for i, name in layout.stubs.items()}


