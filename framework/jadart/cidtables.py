"""Dart cid -> class-name tables, one per numbering era.

Generated by tools/gen_cids.py, which expands runtime/vm/class_id.h with the C preprocessor
at a given SDK tag. Do not hand-edit; regenerate.

There is more than one table because the numbering is not stable. Two things moved it inside
the range jadart supports:

  Dart 2.19      176 predefined cids, and Record still carried a field_names
                 pointer rather than a packed shape.
  Dart 3.0       177 predefined cids. TypeRef was still a class of its own; 3.1
                 removed it, and 3.0 also predates WeakArray.
  Dart 3.1-3.3   176 predefined cids. ExternalOneByteString and ExternalTwoByteString
                 still existed at 95/96; removing them in 3.4 pulled everything above
                 them down by two.
  Dart 3.4-3.5   174 predefined cids. Bytecode was added at cid 19 later, so every cid from
                 19 up is one lower here than in 3.6+.
  Dart 3.6-3.8   175 cids, but UnlinkedCall, MonomorphicSmiableCall and CallSiteData sit at
                 33/34/35 in a different order than they do from 3.9 on.
  Dart 3.9-3.12  175 cids, the order the rest of jadart was written against.

The 3.6-3.8 difference is a permutation rather than a shift, which makes it the dangerous
kind: the alloc pass routes both UnlinkedCall and MonomorphicSmiableCall as FIXED clusters
so it survives, and only the fill pass notices, because their field layouts differ (2 refs
and a byte, against no refs and two varints). A binary carrying either cluster would have
desynced while every gate stayed green.
"""
from __future__ import annotations


class CidTable:
    """A cid numbering, plus the lookups the walk needs in both directions."""

    __slots__ = ("names", "by_name", "num_predefined")

    def __init__(self, names: dict, num_predefined: int):
        self.names = names
        self.by_name = {v: k for k, v in names.items()}
        self.num_predefined = num_predefined

    def name(self, cid: int) -> str:
        return self.names.get(cid, f"cid{cid}")

    def cid(self, name: str) -> int:
        """Cid for a class name. Raises rather than returning a sentinel: a missing name
        means the table is wrong for this epoch, and guessing a cid desyncs the stream."""
        return self.by_name[name]

    def get(self, name: str, default: int = -1) -> int:
        return self.by_name.get(name, default)


